import { writeFile } from "node:fs/promises";
import { feature } from "topojson-client";
import { geoPath, geoOrthographic, geoGraticule10 } from "d3-geo";

const response = await fetch(
  "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json",
);
if (!response.ok)
  throw new Error(`Cannot fetch Natural Earth boundaries: ${response.status}`);
const world = await response.json();
const projection = geoOrthographic()
  .rotate([58, 12])
  .translate([320, 320])
  .scale(270);
const path = geoPath(projection).digits(1);
const countries = feature(world, world.objects.countries).features;
const projected = countries
  .map((f) => ({ id: String(f.id), path: path(f) }))
  .filter((f) => f.path);
const coordinates = Object.fromEntries(
  [
    ["saofrancisco", [-44, -13]],
    ["amazonia", [-62, -5]],
    ["pantanal", [-56, -18]],
  ].map(([id, point]) => [id, projection(point)]),
);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 640"><path d="${path(geoGraticule10())}" fill="none" stroke="#a6c7bc" stroke-width=".45" opacity=".15"/>${projected.map((c) => `<path d="${c.path}" fill="none" stroke="${c.id === "076" ? "#e4e9ce" : "#9bb7a9"}" stroke-width="${c.id === "076" ? ".85" : ".45"}" opacity="${c.id === "076" ? ".65" : ".28"}"/>`).join("")}</svg>`;
await writeFile(
  new URL("../public/assets/boundaries.svg", import.meta.url),
  svg,
);
await writeFile(
  new URL("../src/lib/mapGeometry.ts", import.meta.url),
  `// Generated by scripts/generate-map.mjs.\nexport const regionCoordinates = ${JSON.stringify(coordinates)} as const;\n`,
);
console.log("Projected map geometry and region coordinates generated.");
